package atividade_evandro;

/*
Escreva um programa que use um laço for para simular 7 dias de uma semana (de 1 a 7),
imprimindo "Regar as plantas" a cada dia percorrido pelo laço.
 */

public class PlantaSemana {
    public static void main(String[] args) {

        for (int i = 1 ; i <= 7; i++ ){
            System.out.print(i + " Regar as plantas \n");
        }
    }
    }
